# Об'єктно-орієнтована парадигма
# Головна концепція: програма - результат взаємодії об'єктів
# - підпарадигми: класична (ООП), прототипна
# = класична: типи не змінюються протягом роботи програми
#   об'єкти належать типам: все, що є у об'єкта визначається
#   його типом (склад об'єкту = склад типу)
# = прототипна: об'єкти будуються з прототипу і можуть змінювати
#   склад під час роботи програми. Більш того, змінювати можна
#   прототипи, що відіб'ється на усіх об'єктах, які з них побудовані.
#   (склад об'єкту може відрізнятись від складу прототипу)

class Point :                               # Оголошення класу
    x = 10                                  # Оголошення полів
    y = 20                                  #
                                            # Після оголошення традиційно залишати
                                            # три порожні рядки
                                            #
def main() :
    p = Point()                             # створення об'єкту (без оператора new)
    print(p.x, p.y)                         # 10 20
    p2 = Point()
    print(p2.x, p2.y)                       # 10 20
    print(Point.x, Point.y)                 # 10 20
    # Сладається враження, що поля мають статичний характер
    Point.x = 30
    print(p.x, p.y, p2.x, p2.y)             # 30 20 30 20
    # зміна статичного поля відбилась на всіх об'єктах даного типу
    p.x = 40
    print(p.x, p.y, p2.x, p2.y)             # 40 20 30 20
    print(Point.x, Point.y)                 # 30 20

    # У той же час, p2.x не існує в локальній області і продовжує
    # звертатись до статичної
    # ПІДСУМОК:
    # інструкція p.x = 40 додає до об'єкту "p" нестатичне поле "x"
    p.w = 50  # чи буде помилка звернення до неіснуючого поля?
    print(p.w) # 50 - помилки немає, інструкція створює нове поле
    # чи буде поле w у p2 чи Point?
    # print(p2.w)    AttributeError: 'Point' object has no attribute 'w'
    # print(Point.w) AttributeError: type object 'Point' has no attribute 'w'
    # Чи можна змінювати склад типу під час роботи (після оголошення)?
    Point.v = 60
    print(Point.v)      # 60 - можна
    # чи зміна типу відіб'ється на об'єктах даного класу?
    print(p.v, p2.v)  # 60 60 - так, відбивається
    p.v = 70          # в об'єкті "p" створене локальне поле "v"
    print(p.v, p2.v)  # 70 60
    del p.v
    print(p.v, p2.v)  # 60 60
    del Point.v       #    можна, зникає доступ від усіх об'єктів
    # print(p.v, p2.v) AttributeError: 'Point' object has no attribute 'v'
    # чи можна видалити поле, що введене при оголошенні класу?
    del Point.x       #    можна, але видалення стат. поля не впливає на
    print(p.x)        # 40 існування динамічних полів об'єктів
    # print(p2.x)    AttributeError: 'Point' object has no attribute 'x'
    p2.x = 80         # видалення стат.поля не заважає створити динамічне
    print(p2.x)       # 80


if __name__ == '__main__' :
    main()

